"""
Quiz evaluation -- step 3: LLM-as-judge.

Judges each quiz question generated by evaluate_quiz.py on four
dimensions (Correctness, Clarity, Distractor Quality, Difficulty
Appropriateness), then performs a deterministic topic coverage check
against evaluation/dataset/quiz_eval.json.

Every API call and file operation is wrapped in try/except so a single
failure (rate limit, network error, malformed response, disk issue)
never crashes the whole script. Supports checkpointed/resumable
evaluation: if a judge call fails, previously judged questions are kept
and skipped on the next run; only failed/remaining questions are retried.

Usage:
    uv run python -m evaluation.judge_quiz
    uv run python -m evaluation.judge_quiz --model llama-3.1-8b-instant
"""

import argparse
import json
import logging
import time
from pathlib import Path
from typing import Optional

from pydantic import BaseModel, Field

logging.basicConfig(
    level=logging.INFO,
    format="%(levelname)s: %(message)s",
)

logger = logging.getLogger(__name__)

RESULTS_DIR = Path(__file__).parent / "results"
DATASET_DIR = Path(__file__).parent / "dataset"

QUIZ_RESULTS_PATH = RESULTS_DIR / "quiz_results.json"
JUDGE_RESULTS_PATH = RESULTS_DIR / "quiz_judge_results.json"
JUDGE_SUMMARY_PATH = RESULTS_DIR / "quiz_judge_summary.json"
QUIZ_EVAL_DATASET_PATH = DATASET_DIR / "quiz_eval.json"

# Use the lighter model by default for evaluation to avoid burning the
# llama-3.3-70b-versatile daily token quota (100K TPD on Groq free tier).
DEFAULT_JUDGE_MODEL = "llama-3.1-8b-instant"

MAX_RETRIES = 2
RETRY_BACKOFF_SECONDS = 5


class QuizJudgment(BaseModel):
    correctness: int = Field(..., ge=1, le=5, description="Is the marked answer actually correct given the source material?")
    clarity: int = Field(..., ge=1, le=5, description="Is the question clear and unambiguous?")
    distractor_quality: int = Field(..., ge=1, le=5, description="Are the incorrect options plausible but clearly wrong, not trivially eliminable or duplicated?")
    difficulty_appropriateness: int = Field(..., ge=1, le=5, description="Does the question match the stated difficulty level?")
    notes: str = Field(..., description="Short explanation for the scores.")


def safe_load_pdf(doc_path: Path):
    """Load the source PDF, returning full_text or None on failure."""
    try:
        from backend.document_loader import load_pdf
        _pages, full_text, _doc_id = load_pdf(str(doc_path))
        return full_text
    except Exception as e:
        logger.error("Failed to load document %s: %s", doc_path, e)
        return None


def safe_get_judge_llm(model: str):
    """Build a structured-output LLM client for judging quiz questions.
    Returns None on failure instead of raising.
    """
    try:
        from langchain_groq import ChatGroq
        llm = ChatGroq(model=model, temperature=0)
        return llm.with_structured_output(QuizJudgment)
    except Exception as e:
        logger.error("Failed to initialize judge LLM (model=%s): %s", model, e)
        return None


def build_judge_prompt(question: dict, source_excerpt: str, difficulty: str) -> str:
    options_text = "\n".join(question.get("options", []))
    return f"""You are grading a multiple-choice quiz question generated from a NumPy study document.

Source document excerpt (may be partial):
---
{source_excerpt}
---

Question:
{question.get("question", "")}

Options:
{options_text}

Marked correct answer: {question.get("answer", "")}
Intended difficulty: {difficulty}

Score the question on four dimensions from 1 (poor) to 5 (excellent):
- correctness: is the marked answer actually correct given the source material?
- clarity: is the question clear and unambiguous?
- distractor_quality: are the incorrect options plausible but clearly wrong, not trivially eliminable or duplicated?
- difficulty_appropriateness: does the question match the stated difficulty level?

Provide a short explanation in notes.
"""


def safe_invoke_judge(judge, prompt: str):
    """Call the judge LLM, returning (judgment, error_message).
    Never raises -- exceptions are caught and returned as a message.
    """
    try:
        judgment = judge.invoke(prompt)
        return judgment, None
    except Exception as e:
        return None, str(e)


def load_quiz_results():
    """Load quiz_results.json, returning the dict or None on failure."""
    if not QUIZ_RESULTS_PATH.exists():
        logger.error("Quiz results not found: %s. Run evaluate_quiz first.", QUIZ_RESULTS_PATH)
        return None
    try:
        with open(QUIZ_RESULTS_PATH, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception as e:
        logger.error("Failed to read %s: %s", QUIZ_RESULTS_PATH, e)
        return None


def load_existing_judge_results() -> list:
    if not JUDGE_RESULTS_PATH.exists():
        return []
    try:
        with open(JUDGE_RESULTS_PATH, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception as e:
        logger.warning("Could not read existing %s (%s). Starting fresh.", JUDGE_RESULTS_PATH, e)
        return []


def save_judge_results(results: list) -> bool:
    try:
        RESULTS_DIR.mkdir(parents=True, exist_ok=True)
        with open(JUDGE_RESULTS_PATH, "w", encoding="utf-8") as f:
            json.dump(results, f, indent=2, ensure_ascii=False)
        return True
    except Exception as e:
        logger.error("Failed to save judge results to %s: %s", JUDGE_RESULTS_PATH, e)
        return False


def save_judge_summary(summary: dict) -> bool:
    try:
        RESULTS_DIR.mkdir(parents=True, exist_ok=True)
        with open(JUDGE_SUMMARY_PATH, "w", encoding="utf-8") as f:
            json.dump(summary, f, indent=2, ensure_ascii=False)
        return True
    except Exception as e:
        logger.error("Failed to save judge summary to %s: %s", JUDGE_SUMMARY_PATH, e)
        return False


def load_topic_checklist() -> list:
    if not QUIZ_EVAL_DATASET_PATH.exists():
        logger.warning("Topic checklist not found at %s. Skipping topic coverage.", QUIZ_EVAL_DATASET_PATH)
        return []
    try:
        with open(QUIZ_EVAL_DATASET_PATH, "r", encoding="utf-8") as f:
            return json.load(f).get("topics", [])
    except Exception as e:
        logger.warning("Failed to read topic checklist %s: %s. Skipping topic coverage.", QUIZ_EVAL_DATASET_PATH, e)
        return []


def already_judged_questions(results: list) -> set:
    try:
        return {r["question"] for r in results if r.get("status") == "success"}
    except Exception as e:
        logger.warning("Could not determine already-judged questions: %s", e)
        return set()


def check_topic_coverage(questions: list, topics: list) -> dict:
    try:
        combined_text = " ".join(
            (q.get("question", "") + " " + " ".join(q.get("options", [])))
            for q in questions
        ).lower()

        covered_topics = []
        missing_topics = []

        for topic in topics:
            name = topic.get("name", "unknown")
            keywords = [kw.lower() for kw in topic.get("keywords", [])]
            if any(kw in combined_text for kw in keywords):
                covered_topics.append(name)
            else:
                missing_topics.append(name)

        total = len(topics)
        covered_count = len(covered_topics)

        return {
            "total_topics": total,
            "covered_count": covered_count,
            "coverage_pct": round(100 * covered_count / total, 1) if total else 0.0,
            "covered_topics": covered_topics,
            "missing_topics": missing_topics,
        }
    except Exception as e:
        logger.warning("Topic coverage check failed: %s", e)
        return {}


def main(model: str = DEFAULT_JUDGE_MODEL) -> None:
    # ---------------------------------------------------------
    # 1. Load quiz results
    # ---------------------------------------------------------
    quiz_data = load_quiz_results()
    if quiz_data is None:
        return

    questions = quiz_data.get("questions", [])
    difficulty = quiz_data.get("difficulty", "medium")
    doc_name = quiz_data.get("doc")

    if not questions:
        logger.warning("No questions found in %s. Nothing to judge.", QUIZ_RESULTS_PATH)
        return

    # ---------------------------------------------------------
    # 2. Load source document for correctness grounding
    # ---------------------------------------------------------
    try:
        from config import SAMPLE_DOCS_DIR
        doc_path = SAMPLE_DOCS_DIR / doc_name
    except Exception as e:
        logger.error("Could not resolve SAMPLE_DOCS_DIR from config: %s", e)
        return

    full_text = safe_load_pdf(doc_path)
    if full_text is None:
        logger.error("Cannot proceed without the source document. Aborting.")
        return

    # Keep the excerpt bounded to limit token usage per judge call.
    source_excerpt = full_text[:4000]

    # ---------------------------------------------------------
    # 3. Load topic checklist
    # ---------------------------------------------------------
    topics = load_topic_checklist()

    # ---------------------------------------------------------
    # 4. Resume from previous progress
    # ---------------------------------------------------------
    results = load_existing_judge_results()
    done = already_judged_questions(results)

    if done:
        logger.info("Found %d previously judged question(s). Resuming evaluation.", len(done))

    judge = safe_get_judge_llm(model)
    if judge is None:
        logger.error("Cannot proceed without a working judge LLM. Aborting.")
        return

    total = len(questions)
    for i, q in enumerate(questions, start=1):
        try:
            q_text = q.get("question", "")
        except Exception as e:
            logger.warning("Skipping malformed question at index %d: %s", i, e)
            continue

        if not q_text:
            logger.warning("Skipping question %d/%d with empty text.", i, total)
            continue

        if q_text in done:
            logger.info("Question %d/%d already judged -- skipping.", i, total)
            continue

        logger.info("Judging question %d/%d", i, total)

        prompt = build_judge_prompt(q, source_excerpt, difficulty)

        judgment: Optional[QuizJudgment] = None
        for attempt in range(1, MAX_RETRIES + 1):
            judgment, error_message = safe_invoke_judge(judge, prompt)

            if error_message is None:
                break

            logger.warning(
                "Judge call failed on attempt %d for question %d/%d: %s",
                attempt, i, total, error_message,
            )
            if attempt < MAX_RETRIES:
                try:
                    time.sleep(RETRY_BACKOFF_SECONDS)
                except Exception:
                    pass

        # Remove any stale failed entry for this question before appending
        results = [r for r in results if r.get("question") != q_text]

        if judgment is None:
            results.append({
                "question": q_text,
                "status": "failed",
            })
            logger.error("Question %d/%d could not be judged after %d attempts.", i, total, MAX_RETRIES)
        else:
            try:
                results.append({
                    "question": q_text,
                    "answer": q.get("answer"),
                    "correctness": judgment.correctness,
                    "clarity": judgment.clarity,
                    "distractor_quality": judgment.distractor_quality,
                    "difficulty_appropriateness": judgment.difficulty_appropriateness,
                    "notes": judgment.notes,
                    "status": "success",
                })
            except Exception as e:
                logger.warning("Judgment for question %d/%d was malformed: %s", i, total, e)
                results.append({
                    "question": q_text,
                    "status": "failed",
                })

        # Save progress after every question so a later failure doesn't
        # lose previously completed work.
        saved = save_judge_results(results)
        if not saved:
            logger.error("Could not save progress after question %d/%d. Continuing in-memory.", i, total)

    # ---------------------------------------------------------
    # 5. Build summary
    # ---------------------------------------------------------
    successful = [r for r in results if r.get("status") == "success"]
    failed = [r for r in results if r.get("status") == "failed"]

    def avg(field: str) -> float:
        try:
            vals = [r[field] for r in successful if field in r]
            return round(sum(vals) / len(vals), 2) if vals else 0.0
        except Exception as e:
            logger.warning("Could not average field %s: %s", field, e)
            return 0.0

    coverage = check_topic_coverage(questions, topics) if topics else {}

    summary = {
        "doc": doc_name,
        "model": model,
        "num_questions_judged": len(successful),
        "num_questions_failed": len(failed),
        "average_scores": {
            "correctness": avg("correctness"),
            "clarity": avg("clarity"),
            "distractor_quality": avg("distractor_quality"),
            "difficulty_appropriateness": avg("difficulty_appropriateness"),
        },
        "topic_coverage": coverage,
    }

    save_judge_summary(summary)

    # ---------------------------------------------------------
    # 6. Logging
    # ---------------------------------------------------------
    logger.info("--- Quiz Judge Summary ---")
    logger.info("Judged: %d/%d", len(successful), total)
    logger.info("Failed: %d", len(failed))
    logger.info("Average scores: %s", summary["average_scores"])
    if coverage:
        logger.info(
            "Topic coverage: %d/%d (%.1f%%)",
            coverage.get("covered_count", 0),
            coverage.get("total_topics", 0),
            coverage.get("coverage_pct", 0.0),
        )
    logger.info("Saved judge results to %s", JUDGE_RESULTS_PATH)
    logger.info("Saved judge summary to %s", JUDGE_SUMMARY_PATH)

    if failed:
        logger.warning(
            "%d question(s) failed to judge. Re-run this command to retry them.",
            len(failed),
        )


if __name__ == "__main__":
    try:
        parser = argparse.ArgumentParser(description="Judge quiz questions with an LLM.")
        parser.add_argument(
            "--model",
            default=DEFAULT_JUDGE_MODEL,
            help="Groq model to use for judging (default: llama-3.1-8b-instant to preserve daily quota).",
        )
        args = parser.parse_args()
        main(model=args.model)

    except KeyboardInterrupt:
        logger.warning("Interrupted by user. Progress up to the last saved question is preserved.")
    except Exception as e:
        logger.exception("Unexpected error in judge_quiz: %s", e)