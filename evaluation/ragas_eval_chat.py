import json
from pathlib import Path
from config import EVAL_MODEL, get_groq_api_key, EMBEDDING_MODEL
from ragas.run_config import RunConfig

from ragas import EvaluationDataset, evaluate
from ragas.metrics import (
    Faithfulness,
    AnswerRelevancy,
    ContextPrecision,
    ContextRecall,
)
from ragas.llms import LangchainLLMWrapper
from ragas.embeddings import LangchainEmbeddingsWrapper

from langchain_groq import ChatGroq
from langchain_huggingface import HuggingFaceEmbeddings


# ---------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------

RESULTS_PATH = Path("evaluation/results/chat_results.json")
OUTPUT_PATH = Path("evaluation/results/chat_ragas_results.json")
SUMMARY_PATH = Path("evaluation/results/chat_ragas_summary.json")


# ---------------------------------------------------------------------
# Load previous RAG evaluation results
# ---------------------------------------------------------------------

def load_results():
    """Load the results generated by evaluate_chat.py."""

    with open(RESULTS_PATH, "r", encoding="utf-8") as f:
        results = json.load(f)

    samples = []

    for item in results:
        samples.append(
            {
                "user_input": item["question"],
                "response": item["answer"],
                "retrieved_contexts": [
                    context["content"]
                    for context in item["contexts"]
                ],
                "reference": item["ground_truth"],
            }
        )

    return samples


# ---------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------

def main():

    print("Loading evaluation results...", flush=True)

    samples = load_results()

    print(
        f"Loaded {len(samples)} evaluation samples.",
        flush=True,
    )

    # -----------------------------------------------------------------
    # Create Ragas dataset
    # -----------------------------------------------------------------

    dataset = EvaluationDataset.from_list(samples)

    # -----------------------------------------------------------------
    # Create evaluator LLM
    # -----------------------------------------------------------------

    print("Creating evaluator LLM...", flush=True)

    raw_llm = ChatGroq(
        model=EVAL_MODEL,
        groq_api_key=get_groq_api_key(),
        temperature=0,
        n=1,
    )

    evaluator_llm = LangchainLLMWrapper(raw_llm)

    # -----------------------------------------------------------------
    # Create evaluator embeddings
    # -----------------------------------------------------------------

    print("Creating evaluator embeddings...", flush=True)

    raw_embeddings = HuggingFaceEmbeddings(
        model_name=EMBEDDING_MODEL,
        model_kwargs={
            "device": "cpu",
        },
        encode_kwargs={
            "normalize_embeddings": True,
        },
    )

    evaluator_embeddings = LangchainEmbeddingsWrapper(raw_embeddings)

    # -----------------------------------------------------------------
    # Define Ragas metrics
    # -----------------------------------------------------------------
    # Legacy metrics take no llm/embeddings in the constructor —
    # they're passed once to evaluate() below.
    # strictness=1 on AnswerRelevancy avoids Groq's "n must be at most 1"
    # error (default strictness generates multiple candidates via n>1).

    metrics = [
        Faithfulness(),
        AnswerRelevancy(strictness=1),
        ContextPrecision(),
        ContextRecall(),
    ]

    # -----------------------------------------------------------------
    # Run evaluation
    # -----------------------------------------------------------------

    print("Starting Ragas evaluation...", flush=True)

    result = evaluate(
        dataset=dataset,
        metrics=metrics,
        llm=evaluator_llm,
        embeddings=evaluator_embeddings,
        run_config=RunConfig(
            timeout=180,
            max_workers=2,
        ),
        batch_size=2,
    )

    # -----------------------------------------------------------------
    # Print results
    # -----------------------------------------------------------------

    print("\n" + "=" * 60)
    print("RAGAS EVALUATION RESULTS")
    print("=" * 60)

    print(result)

    # -----------------------------------------------------------------
    # Save summary scores (aggregate metrics only)
    # -----------------------------------------------------------------

    summary = (
        {k: v for k, v in result._repr_dict.items()}
        if hasattr(result, "_repr_dict")
        else dict(result)
    )

    SUMMARY_PATH.parent.mkdir(parents=True, exist_ok=True)

    with open(SUMMARY_PATH, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)

    print(f"\nSummary saved to: {SUMMARY_PATH}", flush=True)

    # -----------------------------------------------------------------
    # Save detailed results
    # -----------------------------------------------------------------

    try:

        df = result.to_pandas()

        OUTPUT_PATH.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        df.to_json(
            OUTPUT_PATH,
            orient="records",
            indent=2,
        )

        print(
            f"\nDetailed results saved to: {OUTPUT_PATH}",
            flush=True,
        )

    except Exception as e:

        print(
            f"\nCould not save detailed results: {e}",
            flush=True,
        )


# ---------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------

if __name__ == "__main__":
    main()